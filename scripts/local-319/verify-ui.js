async page => {
  const assert=(condition,message)=>{if(!condition)throw new Error(message)};
  const steps=[];
  const origin=new URL(page.url()).origin;
  const id=/\/goals\/([^/?]+)/.exec(page.url())[1];
  const goalUrl=origin+'/goals/'+id;
  const readGoal=async()=>await (await page.request.get(origin+'/api/goals/'+id+'?view=r11')).json();
  const fixture=await readGoal();
  assert(origin==='http://127.0.0.1:5319' && fixture.title==='英語の学習' && fixture.totalRequired===12000,'Use only the dedicated synthetic local stack');
  const shiftDate=(date,days)=>{const d=new Date(date+'T00:00:00Z');d.setUTCDate(d.getUTCDate()+days);return d.toISOString().slice(0,10)};
  const dateLabel=date=>Number(date.slice(5,7))+'月'+Number(date.slice(8,10))+'日';
  const firstDate=fixture.recordStartDate, nextDate=shiftDate(firstDate,1), concurrentDate=shiftDate(firstDate,2);
  const futureDate=shiftDate(fixture.today,1);
  const previousMonthDate=shiftDate(fixture.today.slice(0,7)+'-01',-1);
  await page.request.patch(origin+'/api/goals/'+id+'/logs/'+firstDate,{headers:{origin},data:{status:'DONE',amount:30,expectedGoalSettingsRevision:fixture.goalSettingsRevision,expectedHistoryRevision:fixture.historyRevision}});
  const resetToday=await readGoal();
  await page.request.patch(origin+'/api/goals/'+id+'/logs/'+resetToday.today,{headers:{origin},data:{status:'UNRECORDED',expectedGoalSettingsRevision:resetToday.goalSettingsRevision,expectedHistoryRevision:resetToday.historyRevision}});
  await page.goto(goalUrl);
  await page.getByRole('heading',{name:'これまでの積み上げ'}).waitFor();
  const before=await readGoal();
  const chart=page.locator('.fr-today__history-chart');
  await chart.getByRole('button',{name:'全期間',exact:true}).click();
  const svg=chart.locator('svg');
  await svg.focus();await page.keyboard.press('Home');
  assert((await chart.locator('.fr-chart-selection').innerText()).includes(dateLabel(firstDate)),'Home selects record start');
  await page.keyboard.press('ArrowRight');
  assert((await chart.locator('.fr-chart-selection').innerText()).includes(dateLabel(nextDate)),'ArrowRight selects next date');
  await page.keyboard.press('Home');
  await chart.getByRole('link',{name:'この日の記録を見る・編集する'}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  const amount=page.getByRole('textbox',{name:/実施量/});
  assert(await amount.inputValue()==='30','old record initial value must be saved amount 30, not configured 45');
  await amount.fill('0');
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'0は休み・削除へ変換されません'}).waitFor();
  assert((await readGoal()).progressDone===before.progressDone,'invalid zero must not write');
  await amount.fill('55');
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  assert((await readGoal()).progressDone===before.progressDone+25,'past amount correction updates exact cumulative');
  steps.push('chart period and keyboard selection; old saved amount; zero rejection; historical DONE correction');
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('radio',{name:'休んだ',exact:true}).check();
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  assert((await readGoal()).progressDone===before.progressDone-30,'DONE to SKIPPED removes prior amount');
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('radio',{name:'削除して未記録に戻す',exact:true}).check();
  await page.getByRole('button',{name:'削除して未記録に戻す',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  assert((await page.getByRole('region',{name:'選択した日の記録'}).innerText()).includes('未記録'),'deletion is missing, not skipped');
  steps.push('DONE to SKIPPED and deletion to UNRECORDED');
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('textbox',{name:/実施量/}).fill('30');
  // A concurrent real API write must invalidate this editor epoch without overwriting its draft.
  const current=await readGoal();
  const currentLogs=await (await page.request.get(origin+'/api/goals/'+id+'/logs')).json();
  const concurrentAmount=(currentLogs.find(log=>log.localDate===concurrentDate)?.amount ?? 0)+1;
  const concurrent=await page.request.patch(origin+'/api/goals/'+id+'/logs/'+concurrentDate,{headers:{origin},data:{status:'DONE',amount:concurrentAmount,expectedGoalSettingsRevision:current.goalSettingsRevision,expectedHistoryRevision:current.historyRevision}});
  assert(concurrent.status()===200,'concurrent writer fixture');
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'別の画面で記録または設定が変わりました'}).waitFor();
  assert(await page.getByRole('textbox',{name:/実施量/}).inputValue()==='30','conflict retains draft');
  assert(await page.getByRole('button',{name:'記録を保存',exact:true}).isDisabled(),'conflict prevents blind retry');
  await page.getByRole('button',{name:'最新の履歴を読み込む'}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('textbox',{name:/実施量/}).fill('30');
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  steps.push('real concurrent update rejects stale editor, retains draft and requires explicit reload');
  await page.getByRole('button',{name:'今月へ戻る',exact:true}).click();
  if(futureDate.slice(0,7)===fixture.today.slice(0,7)) {
    await page.getByRole('button',{name:new RegExp('^'+dateLabel(futureDate))}).click();
    assert(await page.getByRole('button',{name:'この日の記録を編集',exact:true}).isDisabled(),'future cannot edit');
    assert((await page.getByRole('region',{name:'選択した日の記録'}).innerText()).includes('未来の日付'),'future distinct');
  }
  await page.getByRole('button',{name:'前の月',exact:true}).click();
  await page.getByRole('button',{name:new RegExp('^'+Number(previousMonthDate.slice(5,7))+'月1日 ')}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('textbox',{name:/実施量/}).fill('49');
  await page.route('**/api/goals/*/logs/*',route=>route.request().method()==='PATCH'?route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:{code:'UNAVAILABLE',message:'synthetic failure'}})}):route.continue());
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'保存を確認できませんでした'}).waitFor();
  assert(await page.getByRole('textbox',{name:/実施量/}).inputValue()==='49','failed update retains draft');
  await page.unroute('**/api/goals/*/logs/*');
  await page.getByRole('button',{name:'最新の履歴を読み込む'}).click();
  steps.push('month navigation; future distinction; failed update retains input');
  await page.goto(goalUrl);
  await page.getByRole('heading',{name:'これまでの積み上げ'}).waitFor();
  await page.locator('.fr-today__dock .fr-choice').first().click();
  await page.locator('#fr-recorded-title').waitFor();
  assert((await readGoal()).todayStatus==='DONE','today still saves');
  assert((await page.locator('.fr-save-feedback').textContent()).includes('+45分'),'confirmed delta moves to progress');
  assert(await page.locator('.fr-today__right .fr-save-feedback').count()===1,'delta in right progress panel');
  await page.locator('.fr-save-delta').evaluateAll(elements=>Promise.all(elements.flatMap(element=>element.getAnimations().map(animation=>animation.finished))));
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'.local/319/after-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.local/319/after-mobile.png',fullPage:true});
  steps.push('today save and +45 delta in progress');
  return {steps,goalUrl,before:before.progressDone,after:(await readGoal()).progressDone};
}
