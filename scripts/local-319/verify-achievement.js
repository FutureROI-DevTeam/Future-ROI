async page => {
  const origin='http://127.0.0.1:5319';
  const assert=(condition,message)=>{if(!condition)throw Error(message)};
  const headers={origin,'idempotency-key':await page.evaluate(()=>crypto.randomUUID())};
  const create=await page.request.post(origin+'/api/goals',{headers,data:{title:'ローカル達成境界',unit:'sessions',totalRequired:5,sessionAmount:5,timezone:'Asia/Tokyo'}});
  assert(create.status()===201,'create achievement fixture');
  const goal=await create.json();
  const base=origin+'/api/goals/'+goal.id;
  const read=async()=>await (await page.request.get(base+'?view=r11')).json();
  const initial=await read();
  const saved=await page.request.patch(base+'/logs/'+initial.today,{headers:{origin},data:{status:'DONE',amount:5,expectedGoalSettingsRevision:initial.goalSettingsRevision,expectedHistoryRevision:initial.historyRevision}});
  assert(saved.status()===200,'achievement fixture write');
  await page.goto(origin+'/goals/'+goal.id);
  await page.locator('#fr-achieved-title').waitFor();
  await page.getByRole('link',{name:'履歴をすべて見る・編集する'}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('textbox',{name:/実施量/}).fill('3');
  await page.getByRole('button',{name:'記録を保存',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  assert((await read()).progressDone===3,'achievement correction exact cumulative');
  await page.goto(origin+'/goals/'+goal.id);
  await page.locator('#fr-recorded-title').waitFor();
  assert(await page.locator('#fr-achieved-title').count()===0,'correction returns to incomplete recorded state');
  await page.getByRole('link',{name:'履歴をすべて見る・編集する'}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).click();
  await page.getByRole('radio',{name:'削除して未記録に戻す',exact:true}).check();
  await page.getByRole('button',{name:'削除して未記録に戻す',exact:true}).click();
  await page.getByRole('button',{name:'この日の記録を編集',exact:true}).waitFor();
  await page.goto(origin+'/goals/'+goal.id);
  await page.locator('.fr-today__dock .fr-choice').first().waitFor();
  assert((await read()).todayStatus==='UNRECORDED','deletion restores unrecorded UI');
  const deleted=await page.request.delete(base,{headers:{origin}});assert(deleted.status()===204,'cleanup owned synthetic fixture');
  const tzCreate=await page.request.post(origin+'/api/goals',{headers:{origin,'idempotency-key':await page.evaluate(()=>crypto.randomUUID())},data:{title:'ローカル日付境界',unit:'minutes',totalRequired:100,sessionAmount:10,timezone:'Pacific/Kiritimati'}});
  const tz=await tzCreate.json();
  const tzBase=origin+'/api/goals/'+tz.id;
  assert((await page.request.patch(tzBase,{headers:{origin},data:{timezone:'Etc/GMT+12',expectedGoalSettingsRevision:tz.goalSettingsRevision}})).status()===200,'timezone change before first record');
  await page.goto(origin+'/goals/'+tz.id);
  await page.getByText('表示できる記録日はまだありません。',{exact:false}).waitFor();
  assert(await page.locator('.fr-today__dock .fr-choice').count()===0,'before-start today has no write choices');
  await page.request.delete(tzBase,{headers:{origin}});
  await page.goto(origin+'/goals');
  return {achievedCorrection:true,deletionRestoresUnrecorded:true,startAfterTodayHandled:true,syntheticFixturesDeleted:true};
}
